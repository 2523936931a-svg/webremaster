import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  statSync,
  writeFileSync,
  copyFileSync,
} from "node:fs";
import path from "node:path";
import chalk from "chalk";
import {
  SkinManifestSchema,
  StoreIndexSchema,
  VerificationReportSchema,
  type SkinManifest,
  type StoreIndex,
  type VerificationReport,
} from "@webremaster/schema";

export interface SyncArtifactsOptions {
  skinsDir: string;
  extDir: string;
  storeDir: string;
  minVlmScore?: number;
}

export interface SyncArtifactsResult {
  totalFound: number;
  acceptedCount: number;
  rejectedCount: number;
  storeIndexPath: string;
  registryPath: string;
  acceptedSkins: SkinManifest[];
}

export async function syncArtifactsHandler(
  options: SyncArtifactsOptions,
): Promise<SyncArtifactsResult> {
  const minVlmScore = options.minVlmScore ?? 8.5;
  const skinsDir = path.resolve(options.skinsDir);
  const extDir = path.resolve(options.extDir);
  const storeDir = path.resolve(options.storeDir);

  if (!existsSync(skinsDir)) {
    throw new Error(`Skins 目录不存在: ${skinsDir}`);
  }

  const entries = readdirSync(skinsDir);
  const candidateDirs = entries.filter((entry) => {
    const full = path.join(skinsDir, entry);
    return statSync(full).isDirectory() && existsSync(path.join(full, "manifest.json"));
  });

  const acceptedSkins: SkinManifest[] = [];
  let rejectedCount = 0;

  for (const dirName of candidateDirs) {
    const skinPath = path.join(skinsDir, dirName);
    const manifestPath = path.join(skinPath, "manifest.json");
    const verifPath = path.join(skinPath, "05_verification.json");

    try {
      const manifestRaw = JSON.parse(readFileSync(manifestPath, "utf-8"));
      const manifest = SkinManifestSchema.parse(manifestRaw);

      if (!existsSync(verifPath)) {
        console.warn(chalk.yellow(`[sync-artifacts] ⚠️ 站点 ${dirName} 缺少 05_verification.json，跳过上架`));
        rejectedCount++;
        continue;
      }

      const verifRaw = JSON.parse(readFileSync(verifPath, "utf-8"));
      const verif = VerificationReportSchema.parse(verifRaw);

      if (!verif.passed) {
        console.warn(chalk.yellow(`[sync-artifacts] ⚠️ 站点 ${dirName} 活体验证未全绿 (passed=false)，跳过上架`));
        rejectedCount++;
        continue;
      }

      if (manifest.vlmScore < minVlmScore) {
        console.warn(
          chalk.yellow(
            `[sync-artifacts] ⚠️ 站点 ${dirName} VLM 评分 (${manifest.vlmScore}) 低于门禁线 (${minVlmScore})，跳过上架`,
          ),
        );
        rejectedCount++;
        continue;
      }

      acceptedSkins.push(manifest);
    } catch (err) {
      console.warn(
        chalk.red(`[sync-artifacts] ❌ 站点 ${dirName} 契约校验失败: ${(err as Error).message}`),
      );
      rejectedCount++;
    }
  }

  // 按 VLM 分数降序排列
  acceptedSkins.sort((a, b) => b.vlmScore - a.vlmScore);

  // 1. 同步到 Chrome Extension
  const extSkinsDir = path.join(extDir, "public", "skins");
  mkdirSync(extSkinsDir, { recursive: true });

  const extRegistryDir = path.join(extDir, "src", "registry");
  mkdirSync(extRegistryDir, { recursive: true });
  const registryPath = path.join(extRegistryDir, "skinsRegistry.ts");

  for (const skin of acceptedSkins) {
    const srcUserJs = path.join(skinsDir, skin.id, skin.userscriptFile);
    if (existsSync(srcUserJs)) {
      const targetJs = path.join(extSkinsDir, `${skin.id}.js`);
      copyFileSync(srcUserJs, targetJs);
    }
  }

  const registryContent = `// Automatically generated by WebRemaster wr sync-artifacts. Do not edit manually.
import type { SkinManifest } from "@webremaster/schema";

export const SKIN_REGISTRY: SkinManifest[] = ${JSON.stringify(acceptedSkins, null, 2)};
`;
  writeFileSync(registryPath, registryContent, "utf-8");

  // 2. 同步到 Store
  const storeDataDir = path.join(storeDir, "public", "data");
  mkdirSync(storeDataDir, { recursive: true });
  const storeIndexPath = path.join(storeDataDir, "store_index.json");

  const totalTokensBurned = acceptedSkins.reduce(
    (acc, cur) => acc + (cur.tokensUsedToCompile || 0),
    0,
  );
  const avgVlmScore =
    acceptedSkins.length > 0
      ? Number(
          (
            acceptedSkins.reduce((acc, cur) => acc + cur.vlmScore, 0) /
            acceptedSkins.length
          ).toFixed(1),
        )
      : 0;

  const storeIndex: StoreIndex = {
    version: "0.1.0",
    totalSkins: acceptedSkins.length,
    totalTokensBurned,
    avgVlmScore,
    skins: acceptedSkins,
  };
  StoreIndexSchema.parse(storeIndex);
  writeFileSync(storeIndexPath, JSON.stringify(storeIndex, null, 2), "utf-8");

  // 复制 Store 资产 (skins/<id>/*)
  for (const skin of acceptedSkins) {
    const skinStoreDir = path.join(storeDataDir, "skins", skin.id);
    mkdirSync(skinStoreDir, { recursive: true });

    const filesToCopy = [
      skin.userscriptFile,
      skin.beforeImage,
      skin.afterImage,
      "05_verification.json",
      "manifest.json",
    ];

    for (const f of filesToCopy) {
      const srcFile = path.join(skinsDir, skin.id, f);
      if (existsSync(srcFile)) {
        copyFileSync(srcFile, path.join(skinStoreDir, f));
      }
    }

    // 复制源码
    const srcSubDir = path.join(skinsDir, skin.id, "src");
    if (existsSync(srcSubDir)) {
      const targetSrcDir = path.join(skinStoreDir, "src");
      mkdirSync(targetSrcDir, { recursive: true });
      for (const sf of ["adapter.ts", "SkinApp.tsx", "entry.tsx", "skin.css"]) {
        const srcFile = path.join(srcSubDir, sf);
        if (existsSync(srcFile)) {
          copyFileSync(srcFile, path.join(targetSrcDir, sf));
        }
      }
    }
  }

  console.log(chalk.green(`\n✓ 皮肤产物同步完成！`));
  console.log(
    chalk.cyan(
      `  已上架: ${acceptedSkins.length} 站 | 淘汰/跳过: ${rejectedCount} 站 | 平均 VLM: ${avgVlmScore}分`,
    ),
  );
  console.log(chalk.dim(`  → Chrome 扩展注册表: ${registryPath}`));
  console.log(chalk.dim(`  → 皮肤商店索引库:   ${storeIndexPath}`));

  return {
    totalFound: candidateDirs.length,
    acceptedCount: acceptedSkins.length,
    rejectedCount,
    storeIndexPath,
    registryPath,
    acceptedSkins,
  };
}
